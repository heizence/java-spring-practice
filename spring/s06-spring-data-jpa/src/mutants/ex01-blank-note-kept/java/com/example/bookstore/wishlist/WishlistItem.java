package com.example.bookstore.wishlist;

import java.util.Optional;

import com.example.bookstore.book.Book;
import com.example.bookstore.common.BaseTimeEntity;
import com.example.bookstore.member.Member;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.springframework.util.Assert;

/**
 * A book that a member saved for later, with how much they want it and an optional note. A member has each book on
 * their wishlist at most once (the unique key {@code uk_wishlist_items_member_book}).
 *
 * <h2>The table</h2>
 * The entity maps the table {@code wishlist_items}, which {@code V3__create_wishlist_items.sql} creates:
 * <ul>
 *   <li>{@code id}: generated by MySQL ({@code AUTO_INCREMENT}).</li>
 *   <li>{@code member_id} and {@code book_id}: the member and the book. Load them only when they are used.</li>
 *   <li>{@code priority}: the {@link WishlistPriority}, stored by its name, such as {@code HIGH}.</li>
 *   <li>{@code memo}: the {@link #getNote() note}, or {@code NULL} if there is none. The column has the name the old
 *       shop's database used; in Java it is called {@code note}.</li>
 *   <li>{@code created_at} and {@code updated_at}: filled by JPA auditing, like in the other entities.</li>
 * </ul>
 *
 * <h2>Rules</h2>
 * <ul>
 *   <li>The member, the book and the priority are required.</li>
 *   <li>A note is stored without leading and trailing whitespace. A note that is {@code null}, empty or only
 *       whitespace means "no note" and is stored as {@code NULL}. A note may have at most
 *       {@value #MAX_NOTE_LENGTH} characters (after stripping).</li>
 *   <li>Invalid arguments throw {@link IllegalArgumentException}, and the item stays unchanged.</li>
 * </ul>
 */
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
@Entity
@Table(name = "wishlist_items")
public class WishlistItem extends BaseTimeEntity {

    // equals() and hashCode() are inherited from Object on purpose; BaseTimeEntity explains why.

    public static final int MAX_NOTE_LENGTH = 200;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // LAZY: loading a wishlist item shouldn't load its member and book too. @JoinColumn only documents the column
    // here: "member_id" is already the default (the field name, "_", and the name of the members table's id column).
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "member_id")
    private Member member;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "book_id")
    private Book book;

    // By name: with the default (ORDINAL), adding a priority in the middle of the enum would change the meaning of
    // every row already stored.
    @Enumerated(EnumType.STRING)
    private WishlistPriority priority;

    // The only field whose column name doesn't follow from the field's name.
    @Column(name = "memo")
    private String note;

    private WishlistItem(Member member, Book book, WishlistPriority priority, String note) {
        Assert.notNull(member, "member must not be null");
        Assert.notNull(book, "book must not be null");
        Assert.notNull(priority, "priority must not be null");
        this.member = member;
        this.book = book;
        this.priority = priority;
        this.note = normalizeNote(note);
    }

    /**
     * Puts a book on a member's wishlist.
     *
     * @param note the member's note, or {@code null} for none
     * @return the new item; save it
     * @throws IllegalArgumentException if the member, the book or the priority is {@code null}, or if the note is
     *                                  longer than {@value #MAX_NOTE_LENGTH} characters
     */
    public static WishlistItem add(Member member, Book book, WishlistPriority priority, String note) {
        return new WishlistItem(member, book, priority, note);
    }

    /** The member's note, or empty if there is none. */
    public Optional<String> getNote() {
        return Optional.ofNullable(note);
    }

    /**
     * Changes how much the member wants the book.
     *
     * @throws IllegalArgumentException if {@code priority} is {@code null}
     */
    public void changePriority(WishlistPriority priority) {
        Assert.notNull(priority, "priority must not be null");
        this.priority = priority;
    }

    /**
     * Replaces the note. {@code null} or a blank note removes it.
     *
     * @throws IllegalArgumentException if the note is longer than {@value #MAX_NOTE_LENGTH} characters
     */
    public void changeNote(String note) {
        this.note = normalizeNote(note);
    }

    private static String normalizeNote(String note) {
        if (note == null) {
            return null;
        }
        String stripped = note.strip();
        Assert.isTrue(stripped.length() <= MAX_NOTE_LENGTH,
                () -> "note must be at most %d characters: %d".formatted(MAX_NOTE_LENGTH, stripped.length()));
        return stripped;
    }
}
